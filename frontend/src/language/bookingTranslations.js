// Translations for the booking flow's UI chrome (steps, labels, buttons,
// form fields, confirmation screen).
//
// NOTE — scope boundary: service names, document lists, center names and
// availability data all come from the backend (backend/data/seedData.js)
// in English. This file translates everything AROUND that data — the
// step titles, buttons, form labels — but not the data itself. Fully
// localizing service/document names would mean restructuring the backend
// to serve per-language content, which is a separate follow-up.

function spotsLeft(n, lang) {
  const templates = {
    en: `${n} spot${n === 1 ? '' : 's'} left`,
    ar: `${n} ${n === 1 ? 'مكان متبقٍ' : 'أماكن متبقية'}`,
    hi: `${n} जगह बची`,
    tl: `${n} slot na lang`,
    ur: `${n} ${n === 1 ? 'جگہ باقی' : 'جگہیں باقی'}`,
    bn: `${n}টি স্লট বাকি`,
  }
  return templates[lang] || templates.en
}

